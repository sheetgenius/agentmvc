Rails.application.routes.draw do
  get "health" => "health#show"
  scope :api do
    post "users/login" => "users#login"
    post "users" => "users#create"
    get "user" => "users#show"
    put "user" => "users#update"
    get "user/drafts" => "articles#drafts"
    post "user/exports" => "exports#create"
    get "user/exports/:id" => "exports#show"
    get "profiles/:username" => "profiles#show"
    post "profiles/:username/follow" => "profiles#follow"
    delete "profiles/:username/follow" => "profiles#unfollow"
    get "articles/feed" => "articles#feed"
    get "articles" => "articles#index"
    post "articles" => "articles#create"
    get "articles/:slug" => "articles#show"
    put "articles/:slug" => "articles#update"
    delete "articles/:slug" => "articles#destroy"
    post "articles/:slug/publish" => "articles#publish"
    post "articles/:slug/share" => "shares#create"
    delete "articles/:slug/share" => "shares#destroy"
    get "articles/:slug/comments" => "comments#index"
    post "articles/:slug/comments" => "comments#create"
    delete "articles/:slug/comments/:id" => "comments#destroy"
    post "articles/:slug/favorite" => "favorites#create"
    delete "articles/:slug/favorite" => "favorites#destroy"
    get "tags" => "tags#index"
    get "shares/:id/article" => "shares#show"
    put "shares/:id/article" => "shares#update"
    get "shares/:id/live" => "shares#live"
    match "*unmatched", to: "application#not_found", via: :all
  end
end
